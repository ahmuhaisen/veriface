#!/usr/bin/env node
// Dev-only: create a local API key and a service config for the console and `facelab parity`.
//
//   node tools/console/scripts/dev-setup.mjs            # reuse the existing key if there is one
//   node tools/console/scripts/dev-setup.mjs --rotate   # generate a new key
//
// Writes (both git-ignored via tools/console/.gitignore):
//   tools/console/.env.local      VERIFACE_API_KEY=<key>, VERIFACE_URL=http://127.0.0.1:8080
//   tools/console/.dev/config.toml  service config; stores only sha256(key), as the service requires
//
// Then: veriface run --config tools/console/.dev/config.toml
import { createHash, randomBytes } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const consoleDir = resolve(here, "..");
const repo = resolve(consoleDir, "..", "..");
const envPath = join(consoleDir, ".env.local");
const devDir = join(consoleDir, ".dev");
const configPath = join(devDir, "config.toml");
const rotate = process.argv.includes("--rotate");

function readEnv() {
  if (!existsSync(envPath)) return {};
  return Object.fromEntries(
    readFileSync(envPath, "utf8")
      .split(/\r?\n/)
      .filter((l) => l.includes("=") && !l.startsWith("#"))
      .map((l) => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim()]),
  );
}

const env = readEnv();
let key = env.VERIFACE_API_KEY;
if (!key || rotate) key = randomBytes(32).toString("base64url");
const url = env.VERIFACE_URL || "http://127.0.0.1:8080";
const sha = createHash("sha256").update(key, "utf8").digest("hex");

// Optional ONNX Runtime fetched by service/scripts/fetch-onnxruntime.ps1 (the stub engine does not need it).
let ort = null;
const ortRoot = join(repo, "service", "third_party", "onnxruntime");
if (existsSync(ortRoot)) {
  for (const ver of readdirSync(ortRoot).sort().reverse()) {
    const dll = join(ortRoot, ver, "win-x64", "onnxruntime.dll");
    const so = join(ortRoot, ver, "linux-x64", "libonnxruntime.so.1.28.2");
    if (process.platform === "win32" && existsSync(dll)) ort = dll;
    else if (process.platform !== "win32" && existsSync(so)) ort = so;
    if (ort) break;
  }
}

const toml = (p) => JSON.stringify(p.replaceAll("\\", "/"));
const bind = new URL(url);
mkdirSync(devDir, { recursive: true });

// Dev profile directory: copies of the repo profiles plus a generated, DEV/LAB-ONLY `fixtures` profile
// (= standard with INTER_EYE_DISTANCE min 35 for selfie and document). The public-domain fixtures are 1024 px
// images with faces of 40-56 px inter-eye distance, below standard's 60 px, so under standard every verification
// is `retake` with no score; `fixtures` lets `facelab parity --profile fixtures` compare scores. Never ship it.
// Re-run this script after profiles/ changes to refresh the copies.
const repoProfiles = join(repo, "profiles");
const devProfiles = join(devDir, "profiles");
mkdirSync(devProfiles, { recursive: true });
for (const f of readdirSync(devProfiles)) if (f.endsWith(".yaml")) rmSync(join(devProfiles, f));
for (const f of readdirSync(repoProfiles).filter((x) => x.endsWith(".yaml"))) {
  copyFileSync(join(repoProfiles, f), join(devProfiles, f));
}
const standard = readFileSync(join(repoProfiles, "standard.yaml"), "utf8");
let fixtures = standard
  .replace(/^name: standard$/m, "name: fixtures")
  .replace(/^description: .*$/m, "description: DEV/LAB ONLY. standard with INTER_EYE_DISTANCE min 35, for verification-score parity on the small-face public-domain fixtures. Never ship.");
const before = fixtures;
fixtures = fixtures.replace(/^(\s+INTER_EYE_DISTANCE:\s+\{[^}]*min:\s*)60(\s*\})/gm, "$135$2");
const relaxed = (before.match(/^\s+INTER_EYE_DISTANCE:\s+\{[^}]*min:\s*60\s*\}/gm) ?? []).length;
if (relaxed !== 2 || fixtures === before) {
  console.error(`fixtures profile: expected 2 INTER_EYE_DISTANCE min 60 entries in standard.yaml, found ${relaxed}; not writing it`);
} else {
  writeFileSync(
    join(devProfiles, "fixtures.yaml"),
    "# GENERATED by tools/console/scripts/dev-setup.mjs from profiles/standard.yaml. DEV/LAB ONLY; never ship.\n" + fixtures,
  );
}
writeFileSync(
  configPath,
  [
    "# Generated by tools/console/scripts/dev-setup.mjs. DEV ONLY; never deploy this file.",
    "health_requires_key = false",
    "",
    "[server]",
    `bind = "${bind.hostname}:${bind.port || 8080}"`,
    "max_concurrency = 0",
    "queue_limit = 32",
    "request_timeout_ms = 60000",
    "",
    "[paths]",
    `models = ${toml(join(repo, "models"))}`,
    `profiles = ${toml(devProfiles)}`,
    ...(ort ? [`ort_library = ${toml(ort)}`] : []),
    "",
    "[[api_keys]]",
    'project = "dev-console"',
    `sha256 = "${sha}"`,
    'profiles = ["*"]',
    'default_profile = "standard"',
    "",
    "[metrics]",
    "enabled = true",
    "",
    "[logging]",
    'format = "pretty"',
    'level = "info"',
    "",
  ].join("\n"),
);
writeFileSync(
  envPath,
  [
    "# Generated by scripts/dev-setup.mjs. Local dev key; never commit (git-ignored).",
    `VERIFACE_API_KEY=${key}`,
    `VERIFACE_URL=${url}`,
    "",
  ].join("\n"),
);

console.log(`config:  ${configPath}`);
console.log(`env:     ${envPath}  (key ${rotate || !env.VERIFACE_API_KEY ? "generated" : "reused"})`);
console.log(`sha256:  ${sha}`);
console.log(`ort:     ${ort ?? "not configured (fine for the stub engine)"}`);
console.log(`run:     veriface run --config ${configPath}`);
