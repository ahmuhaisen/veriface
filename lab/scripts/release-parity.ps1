<#
.SYNOPSIS
    Optional release-check step: service-vs-lab parity in release-gate mode (facelab parity --require-complete).

.DESCRIPTION
    Runs the public-domain fixtures through a RUNNING veriface service and compares every result with the lab
    goldens and reference scores (lab/src/facelab/parity.py). Called by face-senior-dev's release-check only when
    -Parity, a service URL and an API key are given.

    Exit codes (never treat 3 as passed):
      0  gate PASSED
      1  gate FAILED, or the parity run crashed (see <Out>/parity.md and stderr)
      3  NOT RUN: a prerequisite is missing (reason on stderr)

    Prerequisites: lab/.venv-mp (python -m facelab golden's environment; lab/README.md), models built
    (models/*.onnx) and goldens in testdata/golden/, a ready service, the API key in the -ApiKeyEnv variable, and
    the -Profile loaded by the service. The default profile `fixtures` is DEV-ONLY (standard with
    INTER_EYE_DISTANCE min 35, generated by tools/console/scripts/dev-setup.mjs into tools/console/.dev/profiles/):
    without it almost every verification is a quality-gated retake and score parity is not exercised.

.EXAMPLE
    $env:VERIFACE_API_KEY = '...'
    powershell -ExecutionPolicy Bypass -File lab/scripts/release-parity.ps1 -Service http://127.0.0.1:8080
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)] [string] $Service,
    [string] $ApiKeyEnv = 'VERIFACE_API_KEY',
    [Alias('Profile')] [string] $ProfileName = 'fixtures',
    [string] $Out = ''
)
$ErrorActionPreference = 'Stop'

function Skip([string] $Reason) {
    [Console]::Error.WriteLine("release-parity: NOT RUN: $Reason")
    exit 3
}

$labDir = Split-Path -Parent $PSScriptRoot
$repoDir = Split-Path -Parent $labDir
$python = Join-Path $labDir '.venv-mp\Scripts\python.exe'
if (-not (Test-Path -LiteralPath $python)) { $python = Join-Path $labDir '.venv-mp/bin/python' }
if (-not (Test-Path -LiteralPath $python)) { Skip 'lab/.venv-mp not found (see lab/README.md)' }
if (-not (Test-Path -LiteralPath (Join-Path $repoDir 'testdata/golden/pipeline'))) { Skip 'testdata/golden not generated' }
if (-not (Get-ChildItem -LiteralPath (Join-Path $repoDir 'models') -Filter '*.onnx' -ErrorAction SilentlyContinue)) {
    Skip 'models/*.onnx not built (python -m facelab models build, or unpack a model pack into models/)'
}
$key = [Environment]::GetEnvironmentVariable($ApiKeyEnv)
if ([string]::IsNullOrEmpty($key)) { Skip "API key variable $ApiKeyEnv is not set" }

$base = $Service.TrimEnd('/')
try {
    $ready = Invoke-WebRequest -UseBasicParsing -Uri "$base/health/ready" -TimeoutSec 10
    if ($ready.StatusCode -ne 200) { Skip "service not ready ($($ready.StatusCode))" }
} catch {
    Skip "service not reachable at $base ($($_.Exception.Message))"
}
try {
    $profiles = Invoke-RestMethod -Uri "$base/v1/profiles" -Headers @{ 'X-API-Key' = $key } -TimeoutSec 10
} catch {
    Skip "GET /v1/profiles failed ($($_.Exception.Message)); is the key valid?"
}
if (-not ($profiles.profiles | Where-Object { $_.name -eq $ProfileName })) {
    Skip "profile '$ProfileName' is not loaded by the service (loaded: $(($profiles.profiles | ForEach-Object name) -join ', '))"
}

$pyArgs = @('-m', 'facelab', 'parity', '--service', $base, '--api-key-env', $ApiKeyEnv, '--profile', $ProfileName, '--require-complete')
if ($Out) { $pyArgs += @('--out', $Out) }
Push-Location $labDir
try {
    & $python @pyArgs
    $code = $LASTEXITCODE
} finally {
    Pop-Location
}
switch ($code) {
    0 { exit 0 }
    1 { exit 1 }
    2 { [Console]::Error.WriteLine('release-parity: the parity run CRASHED; treating as FAILED'); exit 1 }
    default { [Console]::Error.WriteLine("release-parity: unexpected exit code $code; treating as FAILED"); exit 1 }
}
